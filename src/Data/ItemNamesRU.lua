--- Looks up Russian translation for an item name.
--- Supports:
---  1. Exact names and rare templates in map
---  2. Compound "Title, Base" names
---  3. Prefix variations: "Runeforged <Base>", "Runemastered <Base>", "Superior <Base>"
---  4. 2-word rare item names: [Prefix] [Suffix] -> [Suffix_RU] [Prefix_RU] (e.g. "Gloom Charm" -> "Оберег мрака")
---  5. Magic items: [MagicPrefix] [Base] [MagicSuffix]
--- If not found, returns original English name as safe fallback.
---@param enName string|nil
---@return string|nil
function ItemNamesRU:Get(enName)
    if not enName or enName == "" then
        return enName
    end

    -- 1. Exact lookup
    if self.map[enName] then
        return self.map[enName]
    end

    -- 2. Compound "Title, Base"
    local title, base = enName:match("^(.-),%s*(.-)$")
    if title and base then
        local ruTitle = self:Get(title) or title
        local ruBase = self:Get(base) or base
        if ruTitle ~= title or ruBase ~= base then
            return ruTitle .. ", " .. ruBase
        end
    end

    -- 3. Base prefix variations (Runeforged, Runemastered, Superior)
    local rfBase = enName:match("^Runeforged%s+(.+)$")
    if rfBase then
        return "Руннокованый " .. (self:Get(rfBase) or rfBase)
    end
    local rmBase = enName:match("^Runemastered%s+(.+)$")
    if rmBase then
        return "Рунномастерский " .. (self:Get(rmBase) or rmBase)
    end
    local supBase = enName:match("^Superior%s+(.+)$")
    if supBase then
        return "Качественный " .. (self:Get(supBase) or supBase)
    end
    local excBase = enName:match("^Exceptional%s+(.+)$")
    if excBase then
        return "Исключительные " .. (self:Get(excBase) or excBase)
    end
    local flawBase = enName:match("^Flawless%s+(.+)$")
    if flawBase then
        return "Безупречные " .. (self:Get(flawBase) or flawBase)
    end

    -- 4. 2-word rare item dynamic generation: [Prefix] [Suffix]
    local p, s = enName:match("^([%a%-']+)%s+([%a%-']+)$")
    if p and s then
        local ruP = self.rarePrefixes[p]
        local ruS = self.rareSuffixes[s]
        if ruP and ruS then
            return ruS .. " " .. ruP
        end
    end

    -- 5. Magic item prefix + base + suffix
    for mpEn, mpRu in pairs(self.magicPrefixes) do
        local patWithPrefix = "^" .. mpEn:gsub("%-", "%%-") .. "%s+(.+)$"
        local rest = enName:match(patWithPrefix)
        if rest then
            for msEn, msRu in pairs(self.magicSuffixes) do
                local patWithSuffix = "^(.-)%s+" .. msEn:gsub("%-", "%%-") .. "$"
                local mBase = rest:match(patWithSuffix)
                if mBase then
                    local ruBase = self:Get(mBase) or mBase
                    return mpRu .. " " .. ruBase .. " " .. msRu
                end
            end
            local ruBase = self:Get(rest) or rest
            return mpRu .. " " .. ruBase
        end
    end
    for msEn, msRu in pairs(self.magicSuffixes) do
        local patWithSuffix = "^(.-)%s+" .. msEn:gsub("%-", "%%-") .. "$"
        local mBase = enName:match(patWithSuffix)
        if mBase then
            local ruBase = self:Get(mBase) or mBase
            return ruBase .. " " .. msRu
        end
    end

    return enName
end

return ItemNamesRU
